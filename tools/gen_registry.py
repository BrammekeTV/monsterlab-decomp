"""Generate src/game/script_registry.cpp + include/game/script_callbacks.h from the two big
RegisterScriptFunc tables (0x800FB958 and 0x801DC9F4).

    python tools/gen_registry.py

Callbacks already decompiled keep the signature of their definition in src/. All others are
declared `void Name(ScriptCtx*)` with their script type code noted; the type code indexes a
signature table in the script engine that hasn't been decoded yet, so those are provisional.
"""
import glob
import re
import sys

sys.path.insert(0, "tools")
from script_funcs import registrations  # noqa: E402

TABLES = [
    ("fn_800FB958", "RegisterGameScriptFuncs", "0x800FB958"),
    ("RegisterGameScriptFuncs", "RegisterGameScriptFuncs", "0x800FB958"),
    ("fn_801DC9F4", "RegisterEngineScriptFuncs", "0x801DC9F4"),
    ("RegisterEngineScriptFuncs", "RegisterEngineScriptFuncs", "0x801DC9F4"),
]


def existing_signatures():
    """name -> (declaration text, is extern C) for functions defined in src/."""
    sigs = {}
    pat = re.compile(r'^(extern "C" )?((?:static )?[\w\*]+(?: [\w\*]+)*?\**)\s+\**(\w+)\(([^;{)]*)\)\s*\{', re.M)
    for f in glob.glob("src/**/*.cpp", recursive=True):
        src = open(f, encoding="utf-8").read()
        for m in pat.finditer(src):
            ext, ret, name, args = m.groups()
            if ret.startswith("static") or ret in ("return", "else", "if"):
                continue
            sigs[name] = (f"{ret} {name}({args});", bool(ext), f)
    return sigs


def main():
    rows = registrations()
    sigs = existing_signatures()
    out_cpp, out_h = [], []
    seen_decl = set()
    for asm_name, func_name, addr in TABLES:
        entries = [r for r in rows if r[3] == asm_name]
        if not entries:
            continue
        out_cpp.append(f"// {addr}")
        out_cpp.append(f"void {func_name}(void) {{")
        for fn, name, ty, _ in entries:
            out_cpp.append(f'    RegisterScriptFunc("{name}", 0x{ty:X}, (void*){fn});')
            if fn in seen_decl:
                continue
            seen_decl.add(fn)
            if fn in sigs:
                decl, ext, where = sigs[fn]
                out_h.append(("C" if ext else "CPP", f"{decl:<70} // {where.replace(chr(92), '/')}"))
            else:
                out_h.append(("CPP", f"void {fn}(ScriptCtx* ctx);{'':<{max(1, 46 - len(fn))}}// type 0x{ty:X}, unverified"))
        out_cpp.append("}")
        out_cpp.append("")

    h = ["#pragma once",
         "// Script callbacks registered by RegisterGameScriptFuncs / RegisterEngineScriptFuncs.",
         "// Generated by tools/gen_registry.py; 'unverified' signatures are placeholders until the",
         "// function is decompiled (the script type code will tell the real parameters).",
         '#include "game/character.h"',
         ""]
    h += [d for k, d in out_h if k == "CPP"]
    h += ["", 'extern "C" {']
    h += [d for k, d in out_h if k == "C"]
    h += ["}", ""]
    open("include/game/script_callbacks.h", "w", encoding="utf-8").write("\n".join(h))

    cpp = ["// The two main script-function registration tables: every function the level and UI",
           "// scripts can call, by name. Generated by tools/gen_registry.py from the original tables.",
           "// Original: RegisterGameScriptFuncs 0x800FB958 (1589 entries),",
           "//           RegisterEngineScriptFuncs 0x801DC9F4 (223 entries).",
           '#include "game/script_callbacks.h"',
           "",
           'extern "C" s32 RegisterScriptFunc(const char* name, s32 type, void* fn);   // 0x801DC91C',
           ""] + out_cpp
    open("src/game/script_registry.cpp", "w", encoding="utf-8").write("\n".join(cpp))
    print(len(seen_decl), "callbacks declared,", sum(1 for k, _ in out_h if k == "CPP" and "unverified" not in _), "with real signatures")


if __name__ == "__main__":
    main()
