"""Generate the entity factory (0x80071BB4) from its assembly.

    python tools/gen_factory.py     -> src/game/entity_factory.cpp

The function is a binary-search switch on a type-name hash (r4). Every case is
    obj = mem ? mem : Alloc(size); if (obj) Ctor(obj, 6, params, 0); return obj;
The generator reads the compare tree (cmpw r4, r0 with r0 built by lis + addi/subi, or a
"symbol+off" relocation that is really a constant) and each case's size and constructor.
"""
import json
import re
import struct
import sys

FUNC_NAMES = ("CreateEntityByType", "fn_80071BB4")
ALLOC = ("ObjAlloc", "fn_801D4414")


def load():
    import glob
    for f in glob.glob("build/RM7P4F/asm/*_text.s"):
        t = open(f).read()
        for n in FUNC_NAMES:
            m = re.search(r"^\.fn " + n + r", \w+\n(.*?)^\.endfn", t, re.M | re.S)
            if m:
                out = []
                for line in m.group(1).splitlines():
                    lab = re.match(r"^\.(L_[0-9A-F]+):", line)
                    if lab:
                        out.append(("label", lab.group(1)))
                        continue
                    ins = re.sub(r"^/\*.*?\*/\s*", "", line).strip()
                    if ins:
                        out.append(("ins", ins))
                return out
    raise SystemExit("factory not found")


def symbol_addr(sym):
    for line in open("config/RM7P4F/symbols.txt"):
        m = re.match(re.escape(sym) + r" = \.\w+:0x([0-9A-F]+);", line)
        if m:
            return int(m.group(1), 16)
    raise SystemExit(f"unknown symbol {sym}")


def ha(v):
    return ((v + 0x8000) >> 16) & 0xFFFF


def main():
    code = load()
    cases = {}          # hash -> label
    hi = {}
    cur = pending = None
    for kind, x in code:
        if kind != "ins":
            continue
        m = re.match(r"lis (r\d+), (-?0x[0-9a-f]+)$", x)
        if m:
            hi[m.group(1)] = int(m.group(2), 16) & 0xFFFF
            continue
        m = re.match(r"lis (r\d+), (\w+)\+(0x[0-9A-F]+)@ha$", x)
        if m:
            hi[m.group(1)] = ("sym", symbol_addr(m.group(2)) + int(m.group(3), 16))
            continue
        m = re.match(r"(addi|subi) r0, (r\d+), (-?0x[0-9a-f]+)$", x)
        if m and m.group(2) in hi and not isinstance(hi[m.group(2)], tuple):
            v = int(m.group(3), 16)
            base = hi[m.group(2)] << 16
            cur = (base + v if m.group(1) == "addi" else base - v) & 0xFFFFFFFF
            continue
        m = re.match(r"addi r0, (r\d+), \w+\+0x[0-9A-F]+@l$", x)
        if m and isinstance(hi.get(m.group(1)), tuple):
            cur = hi[m.group(1)][1] & 0xFFFFFFFF
            continue
        if x == "cmpw r4, r0":
            pending = cur
            continue
        m = re.match(r"beq \.(L_[0-9A-F]+)$", x)
        if m and pending is not None:
            cases[pending] = m.group(1)
            pending = None
            continue

    # case bodies: label -> (size, ctor)
    bodies = {}
    labels = [i for i, (k, x) in enumerate(code) if k == "label"]
    for i, (k, x) in enumerate(code):
        if k != "label" or x not in set(cases.values()):
            continue
        size = ctor = None
        for k2, y in code[i + 1:i + 40]:
            if k2 != "ins":
                continue
            m = re.match(r"li r3, (0x[0-9a-f]+)$", y)
            if m and size is None:
                size = int(m.group(1), 16)
            m = re.match(r"bl (\S+)$", y)
            if m and m.group(1) not in ALLOC:
                ctor = m.group(1)
                break
        if size is None or ctor is None:
            raise SystemExit(f"case {x}: size/ctor not found")
        bodies[x] = (size, ctor)

    try:
        names = json.load(open("build/hashes.json"))
    except FileNotFoundError:
        names = {}

    by_label = {}
    for h, lab in cases.items():
        by_label.setdefault(lab, []).append(h)

    ctors = sorted(set(c for _, c in bodies.values()))
    src = ["// Entity factory: creates a game object from its hashed class name.",
           "// Generated by tools/gen_factory.py from the original switch (0x80071BB4).",
           '#include "types.h"',
           "",
           'extern "C" {',
           "void* ObjAlloc(u32 size);                       // 0x801D4414"]
    src += [f"void* {c}(void* obj, s32 a, void* params, s32 b);" for c in ctors]
    src += ["}", "",
            "// 0x80071BB4",
            "// `mem` is optional preallocated storage. Returns NULL for unknown types.",
            'extern "C" void* CreateEntityByType(void* mem, u32 typeHash, void* params) {',
            "    u32 size;",
            "    void* (*ctor)(void*, s32, void*, s32);",
            "    switch (typeHash) {"]
    for lab in sorted(by_label, key=lambda l: min(by_label[l])):
        size, ctor = bodies[lab]
        for h in sorted(by_label[lab]):
            n = names.get(f"{h:08X}")
            src.append(f"    case 0x{h:08X}:" + (f"   // \"{n}\"" if n else ""))
        src.append(f"        size = 0x{size:X}; ctor = {ctor}; break;")
    src += ["    default:",
            "        return NULL;",
            "    }",
            "    void* obj = mem;",
            "    if (obj == NULL) obj = ObjAlloc(size);",
            "    if (obj != NULL) ctor(obj, 6, params, 0);",
            "    return obj;",
            "}",
            ""]
    open("src/game/entity_factory.cpp", "w", encoding="utf-8").write("\n".join(src))
    print(len(cases), "type hashes,", len(bodies), "classes")


if __name__ == "__main__":
    main()
